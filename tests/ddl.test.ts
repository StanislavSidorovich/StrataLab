import { describe, expect, it } from 'vitest'
import { DDL_PARAM, MAX_DDL_BYTES, ddlDataFromHash, decodeDdl, encodeDdl, hashWithoutDdl } from '../src/core/ddlLink'
import { createTableSql, planDdl, splitStatements, starterSql } from '../src/core/ddlPlan'

// What StrataSQL's PostgreSQL generator writes (src/core/ddl/postgres.ts there), with the DROP option on.
const STRATA = `-- PostgreSQL DDL for "Online Shop" — generated by StrataSQL from the conceptual model.

-- Drop the previous version
DROP TABLE IF EXISTS order_line CASCADE;
DROP TABLE IF EXISTS customer CASCADE;

-- Table ORDER_LINE
CREATE TABLE order_line (
   order_id             integer          NOT NULL,
   line_no              smallint         NOT NULL,
   qty                  integer          NOT NULL,
   CONSTRAINT pk_order_line PRIMARY KEY (order_id, line_no),
   CONSTRAINT ck_qty CHECK (qty > 0)
);

-- Table "ORDER"
CREATE TABLE "order" (
   order_id             integer          NOT NULL,
   customer_id          integer          NOT NULL,
   status               varchar(10)      NULL,
   CONSTRAINT pk_order PRIMARY KEY (order_id),
   CONSTRAINT ck_status CHECK (status IN ('new', 'paid'))
);

-- Table CUSTOMER
CREATE TABLE customer (
   customer_id          integer          NOT NULL,
   email                varchar(80)      NOT NULL,
   CONSTRAINT pk_customer PRIMARY KEY (customer_id),
   CONSTRAINT ak_email UNIQUE (email)
);

ALTER TABLE order_line
   ADD CONSTRAINT fk_line_order FOREIGN KEY (order_id)
      REFERENCES "order" (order_id);

ALTER TABLE "order"
   ADD CONSTRAINT fk_order_customer FOREIGN KEY (customer_id)
      REFERENCES customer (customer_id);
`

describe('#ddl= link', () => {
  it('round-trips a script', async () => {
    const data = await encodeDdl(STRATA)
    expect(data).toMatch(/^[A-Za-z0-9_-]+$/)
    expect(await decodeDdl(data)).toBe(STRATA)
  })

  it('keeps Cyrillic names and comments', async () => {
    const sql = 'CREATE TABLE "клиент" ("имя" varchar(40) NOT NULL); -- Клиенты магазина «Ёлка»'
    expect(await decodeDdl(await encodeDdl(sql))).toBe(sql)
  })

  it('compresses: a 40-table model fits a link easily', async () => {
    const big = Array.from({ length: 40 }, (_, i) => STRATA.replace(/customer/g, `customer_${i}`)).join('\n')
    const data = await encodeDdl(big)
    expect(data.length).toBeLessThan(big.length / 5)
    expect(data.length).toBeLessThan(30_000)
  })

  it('refuses a damaged link with a readable message', async () => {
    const data = await encodeDdl(STRATA)
    await expect(decodeDdl(data.slice(0, data.length / 2))).rejects.toThrow(/damaged or incomplete/)
    await expect(decodeDdl('not*base64')).rejects.toThrow(/damaged/)
  })

  it('refuses a link that inflates past the limit', async () => {
    const data = await encodeDdl(' '.repeat(MAX_DDL_BYTES + 10))
    expect(data.length).toBeLessThan(20_000)
    await expect(decodeDdl(data)).rejects.toThrow(/too large/)
  })

  it('reads and clears the fragment', () => {
    expect(ddlDataFromHash(`#${DDL_PARAM}=abc-_1`)).toBe('abc-_1')
    expect(ddlDataFromHash('#ds=chinook')).toBeNull()
    expect(ddlDataFromHash('')).toBeNull()
    expect(hashWithoutDdl('#ddl=abc')).toBe('')
    expect(hashWithoutDdl('#ddl=abc&ds=chinook')).toBe('#ds=chinook')
  })
})

describe('DDL plan for DuckDB', () => {
  it('splits statements outside strings and comments', () => {
    expect(splitStatements("-- a; b\nSELECT ';'; /* ; */ SELECT \"x;y\"")).toEqual(["SELECT ';'", 'SELECT "x;y"'])
  })

  it('folds ALTER TABLE foreign keys into CREATE TABLE and orders referenced tables first', () => {
    const plan = planDdl(STRATA)
    expect(plan.title).toBe('Online Shop')
    expect(plan.tables.map((t) => t.name)).toEqual(['customer', 'order', 'order_line'])
    const order = plan.tables[1]
    expect(order.ident).toBe('"order"')
    expect(order.foreignKeys).toEqual([
      { name: 'fk_order_customer', columns: ['customer_id'], refTable: 'customer', refName: 'customer', refColumns: ['customer_id'] },
    ])
    expect(createTableSql(order)).toBe(
      'CREATE TABLE "order" (\n' +
        '   order_id             integer          NOT NULL,\n' +
        '   customer_id          integer          NOT NULL,\n' +
        '   status               varchar(10)      NULL,\n' +
        '   CONSTRAINT pk_order PRIMARY KEY (order_id),\n' +
        "   CONSTRAINT ck_status CHECK (status IN ('new', 'paid')),\n" +
        '   CONSTRAINT fk_order_customer FOREIGN KEY (customer_id) REFERENCES customer (customer_id)\n)',
    )
    expect(plan.extras).toEqual([])
    expect(plan.notes.map((n) => n.message)).toEqual([
      'Not run: StrataLab asks before it replaces a table that already exists',
      'Not run: StrataLab asks before it replaces a table that already exists',
    ])
  })

  it('can leave checks and chosen foreign keys out', () => {
    const t = planDdl(STRATA).tables[1]
    const sql = createTableSql(t, { withoutChecks: true, skip: new Set(t.foreignKeys) })
    expect(sql).not.toMatch(/CHECK|FOREIGN/)
    expect(sql).toMatch(/PRIMARY KEY/)
  })

  it('translates serial, identity, inline references and ON DELETE', () => {
    const plan = planDdl(`
      CREATE TABLE public.dept (id serial PRIMARY KEY, name text);
      CREATE TABLE emp (
        id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
        dept_id integer NOT NULL REFERENCES dept (id) ON DELETE CASCADE,
        boss_id bigint REFERENCES emp
      ) WITH (fillfactor = 70);`)
    const [dept, emp] = plan.tables
    expect(dept.ident).toBe('dept')
    expect(dept.items[0]).toBe('id integer PRIMARY KEY NOT NULL')
    expect(emp.items).toEqual(['id bigint PRIMARY KEY', 'dept_id integer NOT NULL', 'boss_id bigint'])
    expect(emp.foreignKeys.map((f) => [f.columns[0], f.refName, f.refColumns])).toEqual([
      ['dept_id', 'dept', ['id']],
      ['boss_id', 'emp', []],
    ])
    const messages = plan.notes.map((n) => n.message).join('\n')
    expect(messages).toMatch(/serial became integer NOT NULL/)
    expect(messages).toMatch(/GENERATED AS IDENTITY left out/)
    expect(messages).toMatch(/ON DELETE CASCADE left out/)
    expect(messages).toMatch(/WITH \(fillfactor = 70\) after the column list left out/)
  })

  it('breaks a circle of foreign keys and says which one was left out', () => {
    const plan = planDdl(`
      CREATE TABLE a (id int PRIMARY KEY, b_id int);
      CREATE TABLE b (id int PRIMARY KEY, a_id int);
      ALTER TABLE a ADD CONSTRAINT fk_a_b FOREIGN KEY (b_id) REFERENCES b (id);
      ALTER TABLE b ADD CONSTRAINT fk_b_a FOREIGN KEY (a_id) REFERENCES a (id);`)
    expect(plan.tables.map((t) => t.name)).toEqual(['a', 'b'])
    expect(plan.tables[0].foreignKeys).toEqual([])
    expect(plan.tables[1].foreignKeys.map((f) => f.name)).toEqual(['fk_b_a'])
    expect(plan.notes).toHaveLength(1)
    expect(plan.notes[0].message).toMatch(/fk_a_b left out: the tables refer to each other in a circle/)
  })

  it('quotes names that are keywords only in DuckDB', () => {
    const plan = planDdl("CREATE TABLE map (at timestamp NULL, note text, CONSTRAINT pk PRIMARY KEY (at), CHECK (note <> 'at'));")
    const t = plan.tables[0]
    expect(t.ident).toBe('"map"')
    expect(t.name).toBe('map')
    expect(t.items).toEqual(['"at" timestamp NULL', 'note text', 'CONSTRAINT pk PRIMARY KEY ("at")'])
    expect(t.checks).toEqual(["CHECK (note <> 'at')"])
  })

  it('keeps Cyrillic quoted names', () => {
    const plan = planDdl('CREATE TABLE "клиент" ("код" integer NOT NULL, CONSTRAINT "пк" PRIMARY KEY ("код"));')
    expect(plan.tables[0].name).toBe('клиент')
    expect(plan.tables[0].ident).toBe('"клиент"')
  })

  it('passes other statements through and reports foreign keys on tables outside the script', () => {
    const plan = planDdl(`BEGIN;
      CREATE INDEX ix_emp ON emp (dept_id);
      ALTER TABLE elsewhere ADD CONSTRAINT fk FOREIGN KEY (x) REFERENCES y (id);
      COMMIT;`)
    expect(plan.extras).toEqual(['CREATE INDEX ix_emp ON emp (dept_id)'])
    expect(plan.notes[0].message).toMatch(/only add a foreign key while it creates the table/)
  })

  it('opens a tab with one SELECT per table', () => {
    const plan = planDdl(STRATA)
    expect(starterSql(plan, plan.tables)).toBe(
      '-- 3 empty tables from model.quaera.app ("Online Shop"), with their keys.\n-- Select a line and press F5 to run it.\n' +
        'SELECT * FROM customer;\nSELECT * FROM "order";\nSELECT * FROM order_line;\n',
    )
  })
})
